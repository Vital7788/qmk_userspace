static bool shift_held = false;
static bool lshift_held = false;
static bool rshift_held = false;

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case KC_LSFT:
            lshift_held = record->event.pressed;

            if (shift_held && record->event.pressed) {
                register_code(KC_CAPS);
                unregister_code(KC_CAPS);
            }
            shift_held = record->event.pressed;
            return true;
            break;
        case KC_RSFT:
            rshift_held = record->event.pressed;

            if (shift_held && record->event.pressed) {
                register_code(KC_CAPS);
                unregister_code(KC_CAPS);
            }
            shift_held = record->event.pressed;
            return true;
            break;

        case KC_Q:
        case KC_W:
        case KC_E:
        case KC_R:
        case KC_T:

        case KC_A:
        case KC_S:
        case KC_D:
        case KC_F:
        case KC_G:

        case KC_Z:
        case KC_X:
        case KC_C:
        case KC_V:
        case KC_B:
            return !(layer_state_is(_QWERTY) && lshift_held);
            break;

        case KC_Y:
        case KC_U:
        case KC_I:
        case KC_O:
        case KC_P:

        case KC_H:
        case KC_J:
        case KC_K:
        case KC_L:
        case KC_SCLN:

        case KC_N:
        case KC_M:
        case KC_COMM:
        case KC_DOT:
        case KC_SLSH:
            return !(layer_state_is(_QWERTY) && rshift_held);
            break;

        default:
            return true;
    }
}
